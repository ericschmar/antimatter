#!/usr/bin/env python3
"""Regenerate crates/antimatter-theme/src/icons.rs from the Phosphor Icons (MIT) regular weight.

usage: scripts/gen-icons.py PATH/TO/phosphor-svelte/lib   (any dir of Phosphor *.svelte files)
Edit NAMES to change the pack; names are Phosphor's PascalCase component names.
"""
import re, sys, pathlib

NAMES = """TextB TextItalic TextStrikethrough Code CodeBlock Link ListBullets ListNumbers Quotes
PaperPlaneRight Paperclip Smiley At Hash Plus X Check CaretDown CaretRight CaretUp MagnifyingGlass
Gear ArrowClockwise Lock LockOpen Bell BellSlash Trash PencilSimple ArrowBendUpLeft DotsThree
Image File Users User Star PushPin Eye EyeSlash Warning Info""".split()

lib = pathlib.Path(sys.argv[1])
out = ["// GENERATED by scripts/gen-icons.py from Phosphor Icons (MIT, see ICONS-LICENSE). Do not edit.",
       "use rune::Icon;", ""]
for name in NAMES:
    src = (lib / f"{name}.svelte").read_text()
    m = re.search(r'\{:else if weight === "regular"\}\s*(.*?)\s*\{:else if weight === "thin"\}', src, re.S)
    paths = re.findall(r'<path d="([^"]+)"(?: opacity="[^"]+")?\s*/>', m.group(1))
    snake = re.sub(r'(?<!^)(?=[A-Z])', '_', name).upper()
    kebab = snake.lower().replace('_', '-')
    body = "".join(f'<path d="{d}" fill="currentColor"/>' for d in paths)
    out.append(f'pub static {snake}: Icon = Icon {{ name: "ph-{kebab}", view: 256.0, body: r#"{body}"# }};')
pathlib.Path(__file__).resolve().parent.parent.joinpath("crates/antimatter-theme/src/icons.rs").write_text("\n".join(out) + "\n")
print(len(NAMES), "icons")
